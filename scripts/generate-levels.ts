/**
 * Generates, validates and encodes levels 1..300 into `src/game/levels.generated.ts`.
 * Run with `yarn gen:levels`.
 */
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';

import { DIFFICULTY_BANDS, getLevelConfig } from '../src/game/difficulty';
import { generateLevelWithStats, levelSeed } from '../src/game/generator';
import { decodeLevel, encodeLevel } from '../src/game/levelCodec';
import { GENERATION_NODE_CAP, solve } from '../src/game/solver';

const LEVEL_COUNT = 300;
const OUTPUT = join(__dirname, '..', 'src', 'game', 'levels.generated.ts');

interface BandStats {
  label: string;
  levels: number;
  attempts: number;
  maxAttempts: number;
  fallbacks: number;
  pars: number[];
  maxNodes: number;
  ms: number;
}

const bands: BandStats[] = DIFFICULTY_BANDS.map((band) => ({
  label: `${band.first}-${band.last}`,
  levels: 0,
  attempts: 0,
  maxAttempts: 0,
  fallbacks: 0,
  pars: [],
  maxNodes: 0,
  ms: 0,
}));

const bandIndex = (level: number): number => {
  const index = DIFFICULTY_BANDS.findIndex((band) => level <= band.last);
  return index === -1 ? DIFFICULTY_BANDS.length - 1 : index;
};

const started = performance.now();
const encoded: string[] = [];
let maxVerifyNodes = 0;

for (let level = 1; level <= LEVEL_COUNT; level += 1) {
  const levelStart = performance.now();
  const { level: generated, stats } = generateLevelWithStats(
    getLevelConfig(level),
    levelSeed(level),
  );
  const text = encodeLevel(generated);
  const decoded = decodeLevel(text);
  if (encodeLevel(decoded) !== text) {
    throw new Error(`Level ${level} does not round-trip through the codec`);
  }
  const verify = solve(decoded.board, { nodeCap: GENERATION_NODE_CAP });
  if (!verify.solvable) {
    throw new Error(`Level ${level} failed re-verification after decoding`);
  }
  maxVerifyNodes = Math.max(maxVerifyNodes, verify.nodes);
  encoded.push(text);

  const band = bands[bandIndex(level)] as BandStats;
  band.levels += 1;
  band.attempts += stats.attempts;
  band.maxAttempts = Math.max(band.maxAttempts, stats.attempts);
  band.fallbacks += stats.fallback ? 1 : 0;
  band.pars.push(generated.par);
  band.maxNodes = Math.max(band.maxNodes, stats.maxNodes);
  band.ms += performance.now() - levelStart;
}

const body = encoded.map((line) => `  '${line}',`).join('\n');
const source = `// Generated by scripts/generate-levels.ts (yarn gen:levels). Do not edit by hand.
// Format: see src/game/levelCodec.ts.

export const LEVELS: readonly string[] = [
${body}
];
`;
writeFileSync(OUTPUT, source);

const totalMs = performance.now() - started;
console.log(`Generated ${LEVEL_COUNT} levels in ${(totalMs / 1000).toFixed(1)} s`);
console.table(
  bands.map((band) => ({
    band: band.label,
    levels: band.levels,
    attempts: band.attempts,
    'max attempts': band.maxAttempts,
    fallbacks: band.fallbacks,
    'par min': Math.min(...band.pars),
    'par avg': Number((band.pars.reduce((sum, par) => sum + par, 0) / band.pars.length).toFixed(1)),
    'par max': Math.max(...band.pars),
    'max nodes': band.maxNodes,
    seconds: Number((band.ms / 1000).toFixed(1)),
  })),
);
console.log(`Max solver nodes on re-verification: ${maxVerifyNodes}`);
console.log(`Wrote ${OUTPUT} (${Buffer.byteLength(source)} bytes)`);
